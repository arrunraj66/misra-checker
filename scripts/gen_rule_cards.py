#!/usr/bin/env python3
"""Generate one rule card per rule (docs/rule-cards/rule-X.Y.md) plus an index, from the rule sources
and the annotated specs in tests/rulespec. Cards show what is detected, every tested case with its
result, and the documented false positives / false negatives."""
from __future__ import annotations

import argparse
import re
import shutil
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import rulespec  # noqa: E402

OUT = ROOT / "docs" / "rule-cards"
LABEL = {"ok": "Compliant (must stay silent)", "bad": "Violation (must be reported)",
         "gap": "Known false negative (not detected yet)", "fp": "Known false positive"}
STATE = {"pass": "pass", "open": "documented limit", "fail": "FAIL", "fixed": "now fixed: promote"}


def descriptor(rule: str) -> dict:
    path = ROOT / "rules" / "c2012" / f"rule_{int(rule.split('.')[0]):02d}_{int(rule.split('.')[1]):02d}.cpp"
    text = path.read_text()
    meta = {}
    m = re.search(r"RuleCategory::(\w+),\s*Decidability::(\w+),\s*AnalysisScope::(\w+),\s*\{(\w+), (\w+)\},\s*\"([^\"]*)\"", text)
    if m:
        meta = {"category": m[1], "decidability": m[2], "scope": m[3], "topic": m[6]}
    c = re.search(r"Detection contract:\s*(.+)", text)
    meta["contract"] = c[1].strip() if c else ""
    return meta


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--checker", default=str(ROOT / "build" / "misra-checker"))
    ap.add_argument("--clang", default=shutil.which("clang-14") or shutil.which("clang") or "clang")
    args = ap.parse_args()
    specs = rulespec.load_specs(None)
    jobs = [(s["rule"], c) for s in specs for c in s["cases"]]
    with ThreadPoolExecutor(8) as pool:
        results = list(pool.map(lambda j: rulespec.run_case(args.checker, args.clang, j[0], j[1]), jobs))
    by_rule: dict[str, list] = {}
    for (rule, case), res in zip(jobs, results):
        by_rule.setdefault(rule, []).append((case, res))
    OUT.mkdir(parents=True, exist_ok=True)
    index = ["# Rule cards", "", "One card per MISRA C:2012 rule: what the detector reports, every tested case and its",
             "result, and the known false positives and false negatives. Generated by `scripts/gen_rule_cards.py`.", "",
             "| Rule | Category | Cases | Pass | Limits |", "|---|---|---|---|---|"]
    for s in specs:
        rule, rows = s["rule"], by_rule.get(s["rule"], [])
        d = descriptor(rule)
        passed = sum(1 for _, r in rows if r["status"] == "pass")
        limits = [(c, r) for c, r in rows if c.kind in ("gap", "fp")]
        lines = [f"# Rule {rule}", "", f"**Category:** {d.get('category', '?')} · **Decidability:** {d.get('decidability', '?')} · "
                 f"**Scope:** {d.get('scope', '?')} · **Topic:** {d.get('topic', '')}", "",
                 "## What the detector reports", "", s["meta"].get("summary") or d.get("contract", ""), ""]
        if d.get("contract") and d["contract"] != s["meta"].get("summary"):
            lines += ["Detection contract: " + d["contract"], ""]
        lines += ["## Known limits", ""]
        if s["meta"].get("limits"):
            lines += [s["meta"]["limits"], ""]
        if limits:
            for c, r in limits:
                lines.append(f"- **{'False negative' if c.kind == 'gap' else 'False positive'}:** {c.desc} ({STATE[r['status']]})")
            lines.append("")
        elif not s["meta"].get("limits"):
            lines += ["None recorded.", ""]
        lines += ["## Tested cases", "", f"{passed} of {len(rows)} pass.", "", "| Kind | Case | Result |", "|---|---|---|"]
        for c, r in rows:
            lines.append(f"| {LABEL[c.kind]} | {c.desc.replace('|', '/')} | {STATE[r['status']]} |")
        lines += ["", "## Case sources", ""]
        for c, r in rows:
            lines += [f"### {LABEL[c.kind]}: {c.desc}", ""]
            for name, text in c.files.items():
                lines += [f"`{name}`", "", "```c", text.rstrip("\n"), "```", ""]
        (OUT / f"rule-{rule}.md").write_text("\n".join(lines) + "\n")
        index.append(f"| [{rule}](rule-{rule}.md) | {d.get('category', '?')} | {len(rows)} | {passed} | {len(limits)} |")
    (OUT / "README.md").write_text("\n".join(index) + "\n")
    print(f"wrote {len(specs)} rule cards to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
